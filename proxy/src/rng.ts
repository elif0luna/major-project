// Seeded randomness for the proxy. Math.random() is never used, so a given seed
// always produces the same drop/delay decisions.

export type Rng = () => number; // uniform in [0, 1)

// mulberry32: small, fast, good enough statistical quality for simulation.
export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// FNV-1a, used to derive an independent stream per message type from one seed.
export function hashString(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

// Standard normal sample (Box-Muller). 1 - rng() keeps u1 in (0, 1] so log() is finite.
export function normal(rng: Rng): number {
  const u1 = 1 - rng();
  const u2 = rng();
  return Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
}
